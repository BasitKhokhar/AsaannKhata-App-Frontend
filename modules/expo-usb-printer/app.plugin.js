const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Config plugin for expo-usb-printer.
 * -----------------------------------------------------------------------------
 * The module's own AndroidManifest declares the USB host feature, but two things
 * have to land on the APP's manifest instead, which is why this plugin exists:
 *
 *   1. A USB_DEVICE_ATTACHED <intent-filter> on MainActivity, plus the
 *      <meta-data> pointing at a device-filter resource.
 *
 * Android can offer this app as a handler for matching attached printers.
 * Permission is still checked before each connection; grants may be revoked
 * on detach and default-handler behavior varies by Android device.
 *
 *   2. res/xml/usb_device_filter.xml, the device filter itself.
 *
 * Only USB class 7 (the standard USB printer class) is matched. Class 0xFF
 * (vendor-specific), which some cheap clones report instead, is deliberately NOT
 * in the filter: it is so broadly used by unrelated accessories that Android
 * would offer to open AsaanKhata whenever almost anything was plugged in. Those
 * ESC/POS-compatible printers use the runtime permission prompt path in
 * UsbPrinterModule.requestPermission() instead of the default-handler.
 */

const USB_ATTACHED_ACTION = 'android.hardware.usb.action.USB_DEVICE_ATTACHED';
const FILTER_RESOURCE = '@xml/usb_device_filter';
const FILTER_FILENAME = 'usb_device_filter.xml';

const DEVICE_FILTER_XML = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by modules/expo-usb-printer/app.plugin.js — do not edit by hand.

  class 7 is the USB printer class. Android matches this against the device class
  and, when that is 0 (per-interface), against each interface class in turn, so
  this covers the usual "device class 0 + printer interface" thermal printer.
-->
<resources>
  <usb-device class="7" />
</resources>
`;

/** Adds the attach intent-filter + device-filter meta-data to MainActivity. */
const withUsbPrinterManifest = (config) =>
  withAndroidManifest(config, (cfg) => {
    const mainActivity = AndroidConfig.Manifest.getMainActivityOrThrow(cfg.modResults);

    mainActivity['intent-filter'] = mainActivity['intent-filter'] || [];
    const hasFilter = mainActivity['intent-filter'].some((filter) =>
      (filter.action || []).some((action) => action?.$?.['android:name'] === USB_ATTACHED_ACTION)
    );
    if (!hasFilter) {
      mainActivity['intent-filter'].push({
        action: [{ $: { 'android:name': USB_ATTACHED_ACTION } }],
      });
    }

    mainActivity['meta-data'] = mainActivity['meta-data'] || [];
    const hasMeta = mainActivity['meta-data'].some(
      (meta) => meta?.$?.['android:name'] === USB_ATTACHED_ACTION
    );
    if (!hasMeta) {
      mainActivity['meta-data'].push({
        $: { 'android:name': USB_ATTACHED_ACTION, 'android:resource': FILTER_RESOURCE },
      });
    }

    return cfg;
  });

/** Writes res/xml/usb_device_filter.xml into the generated Android project. */
const withUsbPrinterDeviceFilter = (config) =>
  withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml'
      );
      await fs.promises.mkdir(xmlDir, { recursive: true });
      await fs.promises.writeFile(path.join(xmlDir, FILTER_FILENAME), DEVICE_FILTER_XML, 'utf8');
      return cfg;
    },
  ]);

module.exports = function withUsbPrinter(config) {
  return withUsbPrinterDeviceFilter(withUsbPrinterManifest(config));
};
